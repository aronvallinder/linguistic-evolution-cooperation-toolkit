"""
Runner script for djx-managed Donor Game experiments.

Usage (called by djx):
    python experiments/run_donor_djx.py <config_file>

The config_file is a YAML file generated by djx containing all experiment parameters.
"""

import os
import sys

# Add project root to Python path
project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, project_root)

import yaml
from src.donor_simulation import run_donor_simulation
from src.myth_writer import MythWriter
from src.utils import get_default_model
from games.donor_game import DonorGame


def run_from_config(config_path):
    """Run a donor game simulation from a djx-generated config file."""
    with open(config_path, 'r') as f:
        config = yaml.safe_load(f)

    game_params = config.get('game_params', {})
    simulation_params = config.get('simulation_params', {})

    # Build personas dict for all agents
    population_size = game_params.get('population_size', 6)
    persona_addition = config.get('persona_system_addition', '')
    personas = {}
    if persona_addition:
        personas = {
            f'Agent_{i+1}': {
                'description': config.get('persona_name', 'neutral'),
                'system_addition': persona_addition,
            }
            for i in range(population_size)
        }

    # Create game
    game = DonorGame(
        initial_resources=game_params.get('initial_resources', 100),
        donation_multiplier=game_params.get('donation_multiplier', 2),
        population_size=population_size,
        context_depth=game_params.get('context_depth', 2),
        context_width=game_params.get('context_width', 2),
        personas=personas,
    )

    # Create myth writer if myths are in task order
    task_order = simulation_params.get('task_order', ['game'])
    myth_writer = None
    if 'myth' in task_order:
        myth_params = config.get('myth_params', {})
        myth_writer = MythWriter(
            myth_topic=myth_params.get('topic', 'cooperation and generosity'),
            round_1_template=myth_params.get('round_1_template'),
            later_rounds_template=myth_params.get('later_rounds_template'),
        )

    # Resolve model
    model = config.get('model')
    if not model or model == 'default':
        model = get_default_model()

    # Run simulation
    sim_data = run_donor_simulation(
        game=game,
        model=model,
        temperature=simulation_params.get('temperature', 0.8),
        num_turns=simulation_params.get('num_turns', 10),
        memory_capacity=simulation_params.get('memory_capacity', 5),
        agent_biases=None,
        myth_writer=myth_writer,
        task_order=task_order,
        myth_visibility=simulation_params.get('myth_visibility', 'all'),
        myth_partner_rounds=simulation_params.get('myth_partner_rounds', 2),
    )

    # Save results
    output_path = config.get('output_path')
    if output_path:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        sim_data.save_state(output_path)
        print(f"\nSimulation state saved to {output_path}")
    else:
        print("\nNo output_path specified, results not saved.")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python experiments/run_donor_djx.py <config_file>")
        sys.exit(1)

    run_from_config(sys.argv[1])
